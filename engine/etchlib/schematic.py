"""Write a real .kicad_sch for the spec: embedded library symbols, one instance per part,
and a net label on every pin so ERC and netlist export see the same nets as the board."""

from __future__ import annotations

import uuid
from pathlib import Path

from . import sexpr, symbols
from .kicad import footprint_root, symbol_lib_path
from .spec import Spec

Q = sexpr.Q
GRID = 2.54


def _uid(seed: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "etch:" + seed))


def _font():
    return ["effects", ["font", ["size", 1.27, 1.27]]]


def _prop(name: str, value: str, x: float, y: float, hide: bool = False):
    eff = ["effects", ["font", ["size", 1.27, 1.27]]]
    if hide:
        eff.append(["hide", "yes"])
    return ["property", Q(name), Q(value), ["at", x, y, 0], eff]


def _label(net: str, x: float, y: float, angle: float, seed: str):
    just = {
        0: ["justify", "left", "bottom"],
        90: ["justify", "left", "bottom"],
        180: ["justify", "right", "bottom"],
        270: ["justify", "right", "bottom"],
    }[int(angle) % 360]
    # global labels keep net names plain ("VCC", not "/VCC"), so board and schematic nets match
    return [
        "global_label",
        Q(net),
        ["shape", "passive"],
        ["at", x, y, angle],
        ["fields_autoplaced", "yes"],
        ["effects", ["font", ["size", 1.27, 1.27]], just],
        ["uuid", Q(_uid(seed))],
    ]


PWR_FLAG = "power:PWR_FLAG"
_SOURCES = ("power_out",)


def supply_nets(spec: Spec) -> list[str]:
    """Nets the board's power-in connector or battery feeds that have power-input pins on them and no power-output
    pin: KiCad's ERC cannot know a connector pin is a source (it is passive), so each gets a PWR_FLAG, exactly
    as a person drawing the schematic would. A net already driven by a regulator or module output gets none (two
    power outputs on one net are an ERC error), and a power-input pin on a net no connector feeds still fails ERC
    (live-1792273685866: VSYS of a Pico on the J1 rail, "Input Power pin not driven by any Output Power pins")."""
    etypes: dict[str, set[str]] = {}
    for p in spec.parts:
        for pin in symbols.pins(p.lib_id):
            net = p.pins.get(pin.number)
            if net is not None:
                etypes.setdefault(net, set()).add(pin.etype)
    fed: list[str] = []
    for p in spec.parts:
        if (p.spice or {}).get("role") != "power_in":
            continue
        for net in p.pins.values():
            e = etypes.get(net, set())
            if "power_in" in e and not e & set(_SOURCES) and net not in fed:
                fed.append(net)
    return fed


def write_schematic(spec: Spec, out_dir: Path) -> dict[str, str]:
    """Returns {ref: symbol instance uuid} for footprint paths on the board."""
    name = spec.name
    root_uuid = _uid(name + ":root")
    used_libs: dict[str, list] = {}
    for p in spec.parts:
        used_libs.setdefault(p.lib_id, symbols.load(p.lib_id))
    flags = supply_nets(spec)
    if flags:
        used_libs[PWR_FLAG] = symbols.load(PWR_FLAG)

    doc: list = [
        "kicad_sch",
        ["version", 20250114],
        ["generator", Q("etch")],
        ["generator_version", Q("10.0")],
        ["uuid", Q(root_uuid)],
        ["paper", Q("A4")],
        ["title_block", ["title", Q(spec.raw.get("title", name))], ["comment", 1, Q("generated by etch")]],
        ["lib_symbols", *used_libs.values()],
    ]

    sym_uuids: dict[str, str] = {}
    cols = 4
    for i, p in enumerate(spec.parts):
        X = 38.1 + (i % cols) * 12 * GRID
        Y = 38.1 + (i // cols) * 10 * GRID
        su = _uid(f"{name}:{p.ref}")
        sym_uuids[p.ref] = su
        pins = symbols.pins(p.lib_id)
        # one instance per unit (a quad buffer is four gates plus a power unit); single-unit parts get one
        units = sorted({pin.unit for pin in pins if pin.unit > 0}) or [1]
        for k, unit in enumerate(units):
            ux, uy = X + (k % 3) * 4 * GRID, Y + (k // 3) * 4 * GRID
            uu = su if k == 0 else _uid(f"{name}:{p.ref}:unit{unit}")
            upins = [pin for pin in pins if pin.unit in (unit, 0)] if len(units) > 1 else pins
            inst = [
                "symbol",
                ["lib_id", Q(p.lib_id)],
                ["at", ux, uy, 0],
                ["unit", unit],
                ["exclude_from_sim", "no"],
                ["in_bom", "yes"],
                ["on_board", "yes"],
                ["dnp", "no"],
                ["uuid", Q(uu)],
                _prop("Reference", p.ref, ux + 3.81, uy - 3.81),
                _prop("Value", p.value, ux + 3.81, uy + 3.81),
                _prop("Footprint", p.footprint, ux, uy, hide=True),
                _prop("Datasheet", "~", ux, uy, hide=True),
                _prop("Description", "", ux, uy, hide=True),
            ]
            for pin in upins:
                inst.append(["pin", Q(pin.number), ["uuid", Q(_uid(f"{name}:{p.ref}:pin{pin.number}"))]])
            inst.append(
                [
                    "instances",
                    ["project", Q(name), ["path", Q("/" + root_uuid), ["reference", Q(p.ref)], ["unit", unit]]],
                ]
            )
            doc.append(inst)
            for pin in upins:
                net = p.pins.get(pin.number)
                px, py = ux + pin.x, uy - pin.y
                if net is None:
                    doc.append(["no_connect", ["at", px, py], ["uuid", Q(_uid(f"{name}:{p.ref}:nc{pin.number}"))]])
                    continue
                doc.append(_label(net, px, py, (pin.angle + 180) % 360, f"{name}:{p.ref}:lbl{pin.number}"))

    if flags:
        (fp,) = symbols.pins(PWR_FLAG)
        for k, net in enumerate(flags):
            fx, fy = 38.1 + k * 4 * GRID, 25.4
            ref = f"#FLG{k + 1:02d}"
            doc.append(
                [
                    "symbol",
                    ["lib_id", Q(PWR_FLAG)],
                    ["at", fx, fy, 0],
                    ["unit", 1],
                    ["exclude_from_sim", "no"],
                    ["in_bom", "yes"],
                    ["on_board", "yes"],
                    ["dnp", "no"],
                    ["uuid", Q(_uid(f"{name}:{ref}"))],
                    _prop("Reference", ref, fx, fy - 2.54, hide=True),
                    _prop("Value", "PWR_FLAG", fx, fy - 3.81),
                    _prop("Footprint", "", fx, fy, hide=True),
                    _prop("Datasheet", "~", fx, fy, hide=True),
                    _prop("Description", "", fx, fy, hide=True),
                    ["pin", Q(fp.number), ["uuid", Q(_uid(f"{name}:{ref}:pin"))]],
                    [
                        "instances",
                        ["project", Q(name), ["path", Q("/" + root_uuid), ["reference", Q(ref)], ["unit", 1]]],
                    ],
                ]
            )
            doc.append(_label(net, fx + fp.x, fy - fp.y, (fp.angle + 180) % 360, f"{name}:{ref}:lbl"))

    doc.append(["sheet_instances", ["path", Q("/"), ["page", Q("1")]]])
    doc.append(["embedded_fonts", "no"])
    (out_dir / f"{name}.kicad_sch").write_text(sexpr.dump(doc) + "\n")
    _write_lib_tables(spec, out_dir)
    return sym_uuids


def _write_lib_tables(spec: Spec, out_dir: Path) -> None:
    """Project-local library tables so ERC and DRC can compare against the real libraries
    (this Mac has no global sym-lib-table / fp-lib-table)."""
    sym_libs = sorted({p.lib_id.split(":")[0] for p in spec.parts})
    fp_libs = sorted({p.footprint.split(":")[0] for p in spec.parts})
    sym = ["sym_lib_table", ["version", 7]] + [
        [
            "lib",
            ["name", Q(lib)],
            ["type", Q("KiCad")],
            ["uri", Q(str(symbol_lib_path(lib)))],
            ["options", Q("")],
            ["descr", Q("")],
        ]
        for lib in sym_libs
    ]
    fp = ["fp_lib_table", ["version", 7]] + [
        [
            "lib",
            ["name", Q(lib)],
            ["type", Q("KiCad")],
            ["uri", Q(str(footprint_root(lib) / f"{lib}.pretty"))],
            ["options", Q("")],
            ["descr", Q("")],
        ]
        for lib in fp_libs
    ]
    (out_dir / "sym-lib-table").write_text(sexpr.dump(sym) + "\n")
    (out_dir / "fp-lib-table").write_text(sexpr.dump(fp) + "\n")
